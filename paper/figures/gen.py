# One run of the algorithm, replayed with the reference implementation.
#
def leaf_states(V, s, t, w, x, classes):
    """The final test at one leaf: deleted t (neighbour w) and s (successor x), phantoms t of w
    and s of x.  Returns U, W and the states of the loop, as oneHoleFinalTest/twoHoleFinalTest and twoPhantomLoop
    compute them, for the given (only nonempty) class."""
    U = frozenset(V) - {t, s}
    e0, e1 = ekey(w, t), ekey(x, s)
    F = R.findFactor(U, R.dST(x, w)) | {e0, e1}
    G = R.classSearch(U, F, classes[0], classes[1])
    W = U | {t, s}
    steps = [("class", G)]
    while R.cncomp(W, G) > 1:
        H, BS, out = R.runPhase(U, W, len(W) + 1, G, ())
        steps.append(("phase", G, H, BS, out))
        if out[0] in ("stuck", "fuel"):
            break
        G = R.reducePieces(U, W, H, BS, out)
        steps.append(("reduced", G))
    return U, W, (e0, e1), steps


def run_panel(V, U, W, H, phan, dead, labels, hole_cells, hi=None, row=None, scale=0.62):
    b = cells(hole_cells, "holecell")
    if hi:
        b += cells(hi, "hicell")
    b += grid_edges(U)
    if H is not None:
        Hs = frozenset(e for e in H if e not in phan)
        for k, C in enumerate(R.comps(W, H)):
            b += fac_edges([e for e in Hs if R.edge_p(e) in C], PC[k % 4])
    b += edges([eseg(e) for e in phan], "ph")
    if row:
        (x0, y0), (x1, y1) = row
        b += f"\\draw[rowbox] ({x0}+0.12,{y0}+0.12) rectangle ({x1}+0.88,{y1}+0.88);\n"
    b += pts(U) + "".join(f"\\node[miss] at ({x},{y}) {{}};\n" for (x, y) in sorted(dead))
    for (p, txt, pos) in labels:
        b += lab(p, txt, pos)
    return pic(b, scale)


