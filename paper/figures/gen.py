# Labels.
#
def lab1(a, b, c):
    if c[1] <= b - 1:
        return 0 if c[0] <= a - 1 else 1
    return 2 if a <= c[0] else 3


def labD(a, b, c):
    return 3 if b <= c[1] else (1 if c[0] <= a - 1 else 2)


def labU(a, b, c):
    return 1 if c[1] <= b - 1 else (2 if a <= c[0] else 3)


def labL(a, b, c):
    return 1 if a <= c[0] else (2 if b <= c[1] else 0)


def labR(a, b, c):
    return 2 if c[0] <= a - 1 else (0 if c[1] <= b - 1 else 1)


