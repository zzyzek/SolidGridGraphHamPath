def fig_classsearch():
    V = block(7, 5)
    s, t, w, x = (0, 2), (4, 2), (3, 2), (0, 3)
    U = frozenset(V) - {t, s}
    W = U | {t, s}
    phan = [ekey(w, t), ekey(x, s)]
    F = R.findFactor(U, R.dST(x, w)) | set(phan)
    hs = [h for h in R.classRange(U) if R.classSearchOne(U, F, t, h) is not None]
    assert hs == [-1, 0, 1]
    SQ = R.boxSquares(U)

    def rounds(h):
        A = R.kInitA(U, [t], [h])
        out = [A]
        for _ in range(R.kFuel(U)):
            A2 = R.roundA(U, F, A)
            if all(R.toFA(U, A2, c) == R.toFA(U, A, c) for c in SQ):
                break
            A = A2
            out.append(A)
        return out

    def fill(v):
        if v == 0:
            return None
        return f"orng!{min(85, 30 * v)}" if v > 0 else f"pcA!{min(85, 30 * (-v))}"

    def arcs_F():
        # F's arc across every side that is an edge of U (sides between a box square and its
        # neighbours, each side once); other sides have step range [0, 0] and get no arrow.
        out = ""
        for cx in range(-1, 7):
            for cy in range(-1, 5):
                c = (cx, cy)
                for sd in ("t", "r"):
                    e = R.top(c) if sd == "t" else R.rgt(c)
                    d = R.nb(c, sd)
                    if not ((c in SQ) or (d in SQ)):
                        continue
                    if R.IsEdge(U, e):
                        out += arc_arrow(F, c, sd, "arcarrowsm")
        return out

    ARCS = arcs_F()

    def panel(A, H=None, changed=(), bad=(), scale=0.72):
        f = (lambda c: R.toFA(U, A, c))
        b = ""
        for c in SQ:
            col = fill(f(c))
            if col:
                b += f"\\fill[{col}] ({c[0]},{c[1]}) rectangle ({c[0]+1},{c[1]+1});\n"
        b += "\\draw[gray!40] (0,0) grid (6,4);\n"
        for c in around(t):
            b += f"\\draw[black,thick] ({c[0]},{c[1]}) rectangle ({c[0]+1},{c[1]+1});\n"
        for c in changed:
            b += f"\\draw[pcC,very thick] ({c[0]+0.08},{c[1]+0.08}) rectangle ({c[0]+0.92},{c[1]+0.92});\n"
        if H is not None:
            Hs = frozenset(e for e in H if e not in phan)
            for k, C in enumerate(R.comps(W, H)):
                b += fac_edges([e for e in Hs if R.edge_p(e) in C], PC[k % 4])
            b += edges([eseg(e) for e in phan], "ph")
        for e in bad:
            (a1, a2), (b1, b2) = eseg(e)
            b += f"\\draw[red,line width=3pt] ({a1},{a2}) -- ({b1},{b2});\n"
        b += ARCS
        for c in SQ:
            b += f"\\node[font=\\scriptsize,fill=white,fill opacity=0.6,text opacity=1,inner sep=0.5pt] at ({c[0]}+0.5,{c[1]}+0.5) {{${f(c)}$}};\n"
        b += pts_bw(U)
        b += "".join(f"\\node[miss] at ({p[0]},{p[1]}) {{}};\n" for p in (s, t))
        b += lab(t, "$t$", "above right") + lab(s, "$q$", "left")
        return pic(b, scale)

    row1 = [panel([0] * len(R.kInitA(U, [t], [0])), F)]
    cap1 = ["(a) reference $F$"]
    for k, h in enumerate(hs + [2]):
        A = rounds(h)[-1]
        G = R.classSearchOne(U, F, t, h)
        if G is not None:
            assert R.twoPhantomLoop(U, t, s, len(U) + 2, G) is not None
            row1.append(panel(A, G))
            cap1.append(f"({'bcd'[k]}) $h={h}$, {R.cncomp(W, G)} pieces")
        else:
            f = (lambda c: R.toFA(U, A, c))
            bad = [e for c in SQ for e in R.sides(c) if not R.sideOK(U, F, f, e)]
            row1.append(panel(A, None, bad=bad))
            cap1.append(f"(e) $h={h}$, empty")
    rs = rounds(1)
    assert len(rs) == 4
    row2, cap2, prev = [], [], None
    for k, A in enumerate(rs):
        ch = [] if prev is None else [c for c in SQ if R.toFA(U, A, c) != R.toFA(U, prev, c)]
        row2.append(panel(A, None, changed=ch, scale=0.6))
        cap2.append(f"({'fghi'[k]}) " + ("start" if k == 0 else f"round {k}"))
        prev = A
    write("fig_classsearch.tex",
          panel_row(row1[:3], cap1[:3], "\\quad") + "\\\\[6pt]\n" +
          panel_row(row1[3:], cap1[3:], "\\quad") + "\\\\[8pt]\n" +
          panel_row(row2[:2], cap2[:2], "\\quad") + "\\\\[6pt]\n" +
          panel_row(row2[2:], cap2[2:], "\\quad"))


