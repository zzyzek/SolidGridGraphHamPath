HERE = os.path.dirname(os.path.abspath(__file__))


def ed(p, r):
    return (min(p, r), max(p, r))


def pts(P, style="pt"):
    return "".join(f"\\node[{style}] at ({x},{y}) {{}};\n" for (x, y) in sorted(P))


def edges(E, style):
    return "".join(f"\\draw[{style}] ({a[0]},{a[1]}) -- ({b[0]},{b[1]});\n" for (a, b) in E)


def grid_edges(V, style="gedge"):
    out = []
    for (x, y) in sorted(V):
        for (dx, dy) in ((1, 0), (0, 1)):
            if (x + dx, y + dy) in V:
                out.append(((x, y), (x + dx, y + dy)))
    return edges(out, style)


def cells(C, style):
    return "".join(f"\\fill[{style}] ({x},{y}) rectangle ({x+1},{y+1});\n" for (x, y) in C)


def lab(p, text, pos="above left", style="lab"):
    return f"\\node[{style},{pos}] at ({p[0]},{p[1]}) {{{text}}};\n"


def pic(body, scale=0.75):
    return f"\\begin{{tikzpicture}}[scale={scale}]\n{body}\\end{{tikzpicture}}"


def write(name, s):
    with open(os.path.join(HERE, name), "w") as f:
        f.write("% SPDX-License-Identifier: CC0-1.0\n% Generated by gen.py; do not edit by hand.\n" + s + "\n")


def path_edges(seq):
    return [ed(seq[i], seq[i + 1]) for i in range(len(seq) - 1)]


def block(w, h, x0=0, y0=0):
    return {(x, y) for x in range(x0, x0 + w) for y in range(y0, y0 + h)}


