# The strand pairing of a column of length L = 7 (cells c_0..c_6, left vertices v_i = (0,i), right
# w_i = (1,i)), before and after lowering it.  Before: side edge v_i v_{i+1} in H iff i odd, inner
# cross edge v_i w_i (0 < i < L) iff i even, the bottom side v_0 w_0 in H (the dark back of the
# critical cell), the top side v_L w_L not.  Strands leave the column sideways at odd heights, and at
# v_0, w_0 (down) and v_L, w_L (up).  Lowering toggles every side edge and the two end sides; the
# inner cross edges are toggled twice.  Each connected strand gets one colour, keyed by the outside
# stubs it joins, so equal colours before and after mean equal pairing.
#
def fig_strand():
    L = 7

    def state(after):
        E = set()
        for i in range(L):
            if ((i % 2) == 1) != after:
                E.add(((0, i), (0, i + 1)))
                E.add(((1, i), (1, i + 1)))
        for i in range(1, L):
            if (i % 2) == 0:
                E.add(((0, i), (1, i)))
        if not after:
            E.add(((0, 0), (1, 0)))
        else:
            E.add(((0, L), (1, L)))
        return E

    stubs = {}
    for i in range(1, L, 2):
        stubs[("L", i)] = ((0, i), (-0.8, i))
        stubs[("R", i)] = ((1, i), (1.8, i))
    stubs[("L", "bot")] = ((0, 0), (0, -0.8))
    stubs[("R", "bot")] = ((1, 0), (1, -0.8))
    stubs[("L", "top")] = ((0, L), (0, L + 0.8))
    stubs[("R", "top")] = ((1, L), (1, L + 0.8))
    palette = ["pcA", "pcB", "pcC", "pcD", "orng", "teal", "brown", "magenta", "olive", "cyan!70!black"]
    keycol = {}

    def panel(after):
        E = state(after)
        adj = {}
        def link(a, b):
            adj.setdefault(a, set()).add(b)
            adj.setdefault(b, set()).add(a)
        for (p, q) in E:
            link(p, q)
        for k, (p, q) in stubs.items():
            link(p, ("stub", k))
        seen, comps = set(), []
        for v in list(adj):
            if v in seen:
                continue
            C, st = set(), [v]
            while st:
                u = st.pop()
                if u in seen:
                    continue
                seen.add(u)
                C.add(u)
                st.extend(adj[u])
            comps.append(C)
        b = "\\draw[gray!40] (0,0) grid (1,%d);\n" % L
        for C in comps:
            key = frozenset(u[1] for u in C if isinstance(u, tuple) and (u[0] == "stub"))
            if not key:
                col = "black!35"
            else:
                col = keycol.setdefault(key, palette[len(keycol) % len(palette)])
            for (p, q) in E:
                if p in C:
                    b += f"\\draw[{col},line width=2.2pt,line cap=round] ({p[0]},{p[1]}) -- ({q[0]},{q[1]});\n"
            for k, (p, q) in stubs.items():
                if p in C:
                    b += f"\\draw[{col},line width=2.2pt] ({p[0]},{p[1]}) -- ({q[0]},{q[1]});\n"
        b += "".join(f"\\node[pt] at ({x},{y}) {{}};\n" for x in (0, 1) for y in range(L + 1))
        for i in range(L):
            b += f"\\node[cellname] at (0.5,{i}+0.5) {{$c_{i}$}};\n"
        return pic(b, 0.55)

    write("fig_strand.tex", panel_row([panel(False), panel(True)],
                                      ["(a) before lowering", "(b) after lowering"], "\\qquad\\qquad"))


