import hpst_ref as R  # noqa: E402


def hed(x, y):
    return (R.DH, x, y)


def ved(x, y):
    return (R.DV, x, y)


def ekey(p, q):
    if p > q:
        p, q = q, p
    return hed(*p) if q[1] == p[1] else ved(*p)


def eseg(e):
    return (R.edge_p(e), R.edge_q(e))


def fac_edges(F, style):
    return edges([eseg(e) for e in sorted(F)], style)


# Points coloured by the checkerboard: black when x + y is even (Lean `Black`), white otherwise.
#
def pts_bw(P):
    return "".join(f"\\node[{'pt' if R.Black((x, y)) else 'wpt'}] at ({x},{y}) {{}};\n"
                   for (x, y) in sorted(P))


def cells_of(V):
    return [c for c in R.cellList(V)]


# The arc across the side s of cell c, as a short arrow across the side.
#
def arc_arrow(F, c, s, style="arcarrow"):
    x, y = c
    mid = {"t": (x + 0.5, y + 1), "b": (x + 0.5, y), "l": (x, y + 0.5), "r": (x + 1, y + 0.5)}[s]
    d = {"t": (0, 1), "b": (0, -1), "l": (-1, 0), "r": (1, 0)}[s]
    if not R.outArc(F, c, s):
        d = (-d[0], -d[1])
    a = (mid[0] - 0.2 * d[0], mid[1] - 0.2 * d[1])
    b = (mid[0] + 0.2 * d[0], mid[1] + 0.2 * d[1])
    return f"\\draw[{style}] ({a[0]:.2f},{a[1]:.2f}) -- ({b[0]:.2f},{b[1]:.2f});\n"


# All arcs between two cells of V.
#
def all_arcs(V, F):
    out = ""
    for c in cells_of(V):
        for s in ("t", "r"):
            if R.IsCell(V, R.nb(c, s)):
                out += arc_arrow(F, c, s)
    return out


# A height: walk the cells from the first one, +1 along an arc.
#
def heights(V, F):
    cs = cells_of(V)
    tau = {cs[0]: 0}
    st = [cs[0]]
    while st:
        c = st.pop()
        for s in "btlr":
            d = R.nb(c, s)
            if (d in tau) or (not R.IsCell(V, d)):
                continue
            tau[d] = tau[c] + (1 if R.outArc(F, c, s) else -1)
            st.append(d)
    m = min(tau.values())
    return {c: v - m for c, v in tau.items()}


def tau_labels(tau, style="taulab", dy=0.5):
    return "".join(f"\\node[{style}] at ({c[0]}+0.5,{c[1]}+{dy}) {{${v}$}};\n"
                   for c, v in sorted(tau.items()))


# D(F,H)(c): the weights +-2 of the vertical edges of F xor H in the row of c, at or left of
# the left side of c (Definition of D; Lean `D`).
#
def Dval(F, H, c):
    x, y = c
    tot = 0
    for e in (F ^ H):
        if (e[0] == R.DV) and (e[2] == y) and (e[1] <= x):
            tot += (2 if R.up(F, e) else -2)
    return tot


def cycle_edges(seq):
    return frozenset(ekey(seq[i], seq[(i + 1) % len(seq)]) for i in range(len(seq)))


def panel_row(panels, caps, sep="\\quad"):
    cols = ("c@{" + sep + "}") * (len(panels) - 1) + "c"
    body = " & ".join(panels) + " \\\\\n" + " & ".join(f"\\small {c}" for c in caps) + "\n"
    return f"\\begin{{tabular}}{{{cols}}}\n{body}\\end{{tabular}}"


